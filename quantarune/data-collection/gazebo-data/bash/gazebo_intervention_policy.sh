#!/usr/bin/env bash
set -euo pipefail

DATA_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO_ROOT="$(cd "${DATA_ROOT}/.." && pwd)"
PYTHON_BIN="${QUANTARUNE_DATA_PYTHON:-python3}"

cd "${REPO_ROOT}"
export AIC_CHEATCODE_MODE="${AIC_CHEATCODE_MODE:-handoff}"
export AIC_CHEATCODE_HANDOFF_Z_OFFSET_M="${AIC_CHEATCODE_HANDOFF_Z_OFFSET_M:-0.05}"
export AIC_CHEATCODE_HANDOFF_SETTLE_S="${AIC_CHEATCODE_HANDOFF_SETTLE_S:-1.5}"
export AIC_CHEATCODE_EMIT_EPISODE_SIGNALS="${AIC_CHEATCODE_EMIT_EPISODE_SIGNALS:-false}"

echo "Starting intervention policy with:"
echo "  AIC_CHEATCODE_MODE=${AIC_CHEATCODE_MODE}"
echo "  AIC_CHEATCODE_HANDOFF_Z_OFFSET_M=${AIC_CHEATCODE_HANDOFF_Z_OFFSET_M}"
echo "  AIC_CHEATCODE_HANDOFF_SETTLE_S=${AIC_CHEATCODE_HANDOFF_SETTLE_S}"
echo "  AIC_CHEATCODE_EMIT_EPISODE_SIGNALS=${AIC_CHEATCODE_EMIT_EPISODE_SIGNALS}"

exec "${PYTHON_BIN}" quantarune_data/scripts/gazebo_data.py intervention-policy "$@"
